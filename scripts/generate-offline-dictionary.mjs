import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUTPUT = path.resolve("src/data/offlineDictionary5000.generated.ts");
const TARGET_COUNT = 5000;
const FORCE_INCLUDE = [
  "produce", "manager", "architecture", "consequence", "environment", "government",
  "comprehensive", "subtle", "retain", "ambiguous", "mitigate", "development",
];
const SOURCES = [
  "https://raw.githubusercontent.com/thichhoc-org/thichhoc-dict/main/dict-en-vi/data/entries/freq-tier1-01.jsonl",
  "https://raw.githubusercontent.com/thichhoc-org/thichhoc-dict/main/dict-en-vi/data/entries/freq-tier1-02.jsonl",
  "https://raw.githubusercontent.com/thichhoc-org/thichhoc-dict/main/dict-en-vi/data/entries/freq-tier1-03.jsonl",
  "https://raw.githubusercontent.com/thichhoc-org/thichhoc-dict/main/dict-en-vi/data/entries/freq-tier1-04.jsonl",
  // Tier 1 contains just under 5k unique normalized headwords. These two
  // general shards supply the small remainder and guarantee coverage for
  // high-value words such as "produce" without bloating the shipped subset.
  "https://raw.githubusercontent.com/thichhoc-org/thichhoc-dict/main/dict-en-vi/data/entries/general-a-01.jsonl",
  "https://raw.githubusercontent.com/thichhoc-org/thichhoc-dict/main/dict-en-vi/data/entries/general-p-05.jsonl",
];

const HEADER = `// AUTO-GENERATED by scripts/generate-offline-dictionary.mjs\n// Source: thichhoc-org/thichhoc-dict (CC BY-SA 4.0). Do not edit manually.\n`;

function validHeadword(value) {
  return typeof value === "string" && /^[a-z][a-z' -]{0,47}$/i.test(value.trim());
}

function compactStrings(value, max = 3) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map((item) => String(item || "").trim()).filter(Boolean))].slice(0, max);
}

async function fetchText(url) {
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), 15000);
      const response = await fetch(url, {
        signal: controller.signal,
        headers: { "User-Agent": "LexiGlass-build" },
      });
      clearTimeout(timer);
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      return await response.text();
    } catch (error) {
      lastError = error;
      if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, attempt * 700));
    }
  }
  throw new Error(`Unable to download ${url}: ${String(lastError)}`);
}

async function alreadyGenerated() {
  try {
    const current = await readFile(OUTPUT, "utf8");
    return current.includes(`OFFLINE_DICTIONARY_5000_COUNT = ${TARGET_COUNT}`);
  } catch {
    return false;
  }
}

if (await alreadyGenerated()) {
  console.log(`[offline-dict] ${TARGET_COUNT} entries already generated; skipping download.`);
  process.exit(0);
}

console.log("[offline-dict] downloading open English-Vietnamese frequency-tier data...");
const texts = await Promise.all(SOURCES.map(fetchText));
const rows = [];
for (const text of texts) {
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    try {
      const row = JSON.parse(line);
      if (!validHeadword(row.headword)) continue;
      if (!Array.isArray(row.senses_vi) || !row.senses_vi.some(Boolean)) continue;
      rows.push(row);
    } catch {
      // Ignore a malformed JSONL line; the rest of the upstream dataset stays usable.
    }
  }
}

const grouped = new Map();
for (const row of rows) {
  const word = row.headword.trim().toLowerCase().replace(/\s+/g, " ");
  const existing = grouped.get(word) || {
    word,
    freq: Number(row.freq || 0),
    parts: [],
    aliases: new Set(),
  };
  existing.freq = Math.max(existing.freq, Number(row.freq || 0));
  for (const form of compactStrings(row.inflections, 8)) {
    const alias = form.toLowerCase().replace(/\s+/g, " ");
    if (validHeadword(alias) && alias !== word) existing.aliases.add(alias);
  }
  if (existing.parts.length < 3) {
    existing.parts.push({
      p: String(row.pos || "general"),
      i: typeof row.pron === "string" && row.pron.trim() ? row.pron.trim() : undefined,
      v: compactStrings(row.senses_vi, 3),
      e: compactStrings(row.gloss_en?.length ? row.gloss_en : row.senses_en, 3),
      f: compactStrings(row.inflections, 6),
    });
  }
  grouped.set(word, existing);
}

const ranked = [...grouped.values()].sort((a, b) => b.freq - a.freq || a.word.localeCompare(b.word));
const selectedMap = new Map();
for (const word of FORCE_INCLUDE) {
  const entry = grouped.get(word);
  if (entry) selectedMap.set(word, entry);
}
for (const entry of ranked) {
  if (selectedMap.size >= TARGET_COUNT) break;
  if (!selectedMap.has(entry.word)) selectedMap.set(entry.word, entry);
}
const selected = [...selectedMap.values()].sort((a, b) => a.word.localeCompare(b.word));

if (selected.length !== TARGET_COUNT) {
  throw new Error(`Expected ${TARGET_COUNT} offline words/phrases but only produced ${selected.length}.`);
}

const dictionary = {};
const aliases = {};
for (const item of selected) {
  dictionary[item.word] = item.parts;
  for (const alias of item.aliases) {
    if (!dictionary[alias] && !aliases[alias]) aliases[alias] = item.word;
  }
}

await mkdir(path.dirname(OUTPUT), { recursive: true });
const output = `${HEADER}export const OFFLINE_DICTIONARY_5000_COUNT = ${TARGET_COUNT};\nexport const OFFLINE_DICTIONARY_5000 = ${JSON.stringify(dictionary)};\nexport const OFFLINE_DICTIONARY_ALIASES = ${JSON.stringify(aliases)};\n`;
await writeFile(OUTPUT, output, "utf8");
console.log(`[offline-dict] generated ${selected.length} headwords/phrases and ${Object.keys(aliases).length} inflection aliases.`);
console.log(`[offline-dict] forced coverage: ${FORCE_INCLUDE.filter((word) => dictionary[word]).join(", ")}`);
console.log(`[offline-dict] output ${(Buffer.byteLength(output) / 1024 / 1024).toFixed(2)} MiB -> ${OUTPUT}`);
