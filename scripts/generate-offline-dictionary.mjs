function validHeadword(value) {
  if (typeof value !== "string") return false;
  const text = value.normalize("NFKC").trim();
  if (!text || text.length > 80 || !/[a-z0-9]/i.test(text)) return false;
  // Keep normal dictionary punctuation instead of silently dropping entries
  // such as 24/7, 9/11, a/c, dot-com, C++, and similar headwords.
  return /^[a-z0-9 .,'’/&+()#:%-]+$/i.test(text);
}

function compactStrings(value, max = 3) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map((item) => String(item || "").trim()).filter(Boolean))].slice(0, max);
}

function normalizeWord(value) {
  return String(value || "")
    .normalize("NFKC")
    .trim()
    .toLowerCase()
    .replace(/[’‘]/g, "'")
    .replace(/\s+/g, " ");
}

async function fetchResponse(url, timeoutMs = 20000) {
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    try {
      const response = await fetch(url, {
        signal: controller.signal,
        headers: {
          "User-Agent": "LexiGlass-build",
          Accept: "*/*",
        },
      });
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      return response;
    } catch (error) {
      lastError = error;
      if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, attempt * 700));
    } finally {
      clearTimeout(timer);
    }
  }
  throw new Error(`Unable to download ${url}: ${String(lastError)}`);
}

async function fetchText(url, timeoutMs = 20000) {
  return await (await fetchResponse(url, timeoutMs)).text();
}

async function fetchBuffer(url, timeoutMs = 25000) {
  return Buffer.from(await (await fetchResponse(url, timeoutMs)).arrayBuffer());
}

async function forEachGzipJsonLine(url, onRow, timeoutMs = 60000) {
  const response = await fetchResponse(url, timeoutMs);
  if (!response.body) throw new Error(`No response body for ${url}`);

  const input = Readable.fromWeb(response.body).pipe(createGunzip());
  const lines = createInterface({ input, crlfDelay: Infinity });
  let parsed = 0;

  for await (const line of lines) {
    if (!line.trim()) continue;
    try {
      await onRow(JSON.parse(line));
      parsed += 1;
    } catch {
      // One malformed Wiktionary row must not abort the entire dictionary build.
    }
  }
  return parsed;
}

function wiktionaryExamples(row) {
  const output = [];
  const senses = Array.isArray(row?.senses) ? row.senses : [];
  for (const sense of senses) {
    for (const example of Array.isArray(sense?.examples) ? sense.examples : []) {
      const english = String(example?.text || example?.example || "").trim();
      const translated = Array.isArray(example?.translations)
        ? String(example.translations[0] || "").trim()
        : "";
      const vietnamese = String(example?.translation || translated || "").trim();
      if (!english || !vietnamese || english.length < 4 || english.length > 220) continue;
      if (output.some(([existing]) => existing === english)) continue;
      output.push([english, vietnamese]);
      if (output.length >= 2) return output;
    }
  }
  return output;
}

function wiktionaryMeanings(row) {
  const glosses = [];
  for (const sense of Array.isArray(row?.senses) ? row.senses : []) {
    for (const gloss of Array.isArray(sense?.glosses) ? sense.glosses : []) {
      const value = String(gloss || "").trim();
      if (value && !glosses.includes(value)) glosses.push(value);
      if (glosses.length >= 4) return glosses;
    }
  }
  return glosses;
}

function wiktionaryForms(row) {
  const forms = [];
  for (const item of Array.isArray(row?.forms) ? row.forms : []) {
    const form = normalizeWord(item?.form);
    if (!form || !validHeadword(form) || forms.includes(form)) continue;
    forms.push(form);
    if (forms.length >= 12) break;
  }
  return forms;
}

function wiktionaryIpa(row) {
  for (const sound of Array.isArray(row?.sounds) ? row.sounds : []) {
    const ipa = String(sound?.ipa || "").trim();
    if (ipa) return ipa;
  }
  return undefined;
}

async function mapLimit(items, limit, mapper) {
  const results = new Array(items.length);
  let cursor = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (true) {
      const index = cursor++;
      if (index >= items.length) break;
      results[index] = await mapper(items[index], index);
    }
  });
  await Promise.all(workers);
  return results;
}

async function alreadyGenerated() {
  try {
    const current = await readFile(OUTPUT, "utf8");
    const meta = JSON.parse(await readFile(OUTPUT_META_JSON, "utf8"));
    const version = current.match(/OFFLINE_DICTIONARY_SCHEMA_VERSION = (\d+)/);
    const count = current.match(/OFFLINE_DICTIONARY_10000_COUNT = (\d+)/);
    return Boolean(
      version &&
      Number(version[1]) === DATA_SCHEMA_VERSION &&
      count &&
      Number(count[1]) >= MIN_EXPECTED_COUNT &&
      Number(meta?.schemaVersion) === DATA_SCHEMA_VERSION &&
      Number(meta?.headwordCount) >= MIN_EXPECTED_COUNT
    );
  } catch {
    return false;
  }
}

function dictionarySourceUrls() {
  const files = [
    "freq-tier1-01.jsonl",
    "freq-tier1-02.jsonl",
    "freq-tier1-03.jsonl",
    "freq-tier1-04.jsonl",
  ];

  for (const [letter, count] of Object.entries(GENERAL_SHARD_COUNTS)) {
    for (let index = 1; index <= count; index += 1) {
      files.push(`general-${letter}-${String(index).padStart(2, "0")}.jsonl`);
    }
  }
  for (const letter of SINGLE_GENERAL_SHARDS) files.push(`general-${letter}.jsonl`);
  files.push("general-other.jsonl");

  return files.map(
    (file) => `https://raw.githubusercontent.com/${THICHHOC_REPO}/main/${THICHHOC_ENTRIES_PREFIX}${file}`,
  );
}

function extractTextFileFromZip(buffer) {
  let eocd = -1;
  const minOffset = Math.max(0, buffer.length - 65557);
  for (let offset = buffer.length - 22; offset >= minOffset; offset -= 1) {
    if (buffer.readUInt32LE(offset) === 0x06054b50) {
      eocd = offset;
      break;
    }
  }
  if (eocd < 0) throw new Error("ZIP end-of-central-directory record was not found.");

  const totalEntries = buffer.readUInt16LE(eocd + 10);
  let centralOffset = buffer.readUInt32LE(eocd + 16);
  const candidates = [];

  for (let index = 0; index < totalEntries; index += 1) {
    if (buffer.readUInt32LE(centralOffset) !== 0x02014b50) break;
    const method = buffer.readUInt16LE(centralOffset + 10);
    const compressedSize = buffer.readUInt32LE(centralOffset + 20);
    const uncompressedSize = buffer.readUInt32LE(centralOffset + 24);
    const fileNameLength = buffer.readUInt16LE(centralOffset + 28);
    const extraLength = buffer.readUInt16LE(centralOffset + 30);
    const commentLength = buffer.readUInt16LE(centralOffset + 32);
    const localOffset = buffer.readUInt32LE(centralOffset + 42);
    const fileName = buffer
      .subarray(centralOffset + 46, centralOffset + 46 + fileNameLength)
      .toString("utf8");

    if (/\.txt$/i.test(fileName) && !/\/\s*$/.test(fileName)) {
      candidates.push({ fileName, method, compressedSize, uncompressedSize, localOffset });
    }
    centralOffset += 46 + fileNameLength + extraLength + commentLength;
  }

  const target = candidates.find((item) => /(^|\/)vie\.txt$/i.test(item.fileName))
    || candidates.sort((a, b) => b.uncompressedSize - a.uncompressedSize)[0];
  if (!target) throw new Error("No text corpus was found inside the Tatoeba ZIP archive.");

  const local = target.localOffset;
  if (buffer.readUInt32LE(local) !== 0x04034b50) throw new Error("Invalid ZIP local file header.");
  const localNameLength = buffer.readUInt16LE(local + 26);
  const localExtraLength = buffer.readUInt16LE(local + 28);
  const dataStart = local + 30 + localNameLength + localExtraLength;
  const compressed = buffer.subarray(dataStart, dataStart + target.compressedSize);

  if (target.method === 0) return compressed.toString("utf8");
  if (target.method === 8) return inflateRawSync(compressed).toString("utf8");
  throw new Error(`Unsupported ZIP compression method ${target.method}.`);
}

function buildExampleIndex(corpusText, selectedWords, aliases) {
  const examples = new Map();
  const tokenPattern = /[A-Za-z]+(?:['-][A-Za-z]+)*/g;

  for (const line of corpusText.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const columns = line.split("\t");
    if (columns.length < 2) continue;
    const english = columns[0]?.trim();
    const vietnamese = columns[1]?.trim();
    if (!english || !vietnamese || english.length < 8 || english.length > 180) continue;

    const resolvedInSentence = new Set();
    const tokens = english.match(tokenPattern) || [];
    for (const rawToken of tokens) {
      const token = rawToken.toLowerCase();
      const baseWord = selectedWords.has(token) ? token : aliases[token];
      if (!baseWord || resolvedInSentence.has(baseWord)) continue;
      resolvedInSentence.add(baseWord);

      const current = examples.get(baseWord) || [];
      if (current.length >= 2 || current.some(([existing]) => existing === english)) continue;
      current.push([english, vietnamese]);
      examples.set(baseWord, current);
    }
  }

  return examples;
}

if (await alreadyGenerated()) {
  console.log("[offline-dict] full dictionary already generated; skipping download.");
  process.exit(0);
}

const sourceUrls = dictionarySourceUrls();
console.log(`[offline-dict] downloading ${sourceUrls.length} English-Vietnamese dictionary shards...`);
const texts = await mapLimit(sourceUrls, 14, async (url) => {
  try {
    return await fetchText(url, 25000);
  } catch (error) {
    console.warn(`[offline-dict] skipped unavailable shard: ${url} (${String(error)})`);
    return "";
  }
});

const rows = [];
for (const text of texts) {
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    try {
      const row = JSON.parse(line);
      if (!validHeadword(row.headword)) continue;
      if (!Array.isArray(row.senses_vi) || !row.senses_vi.some(Boolean)) continue;
      rows.push(row);
    } catch {
      // Keep processing the rest of an upstream JSONL shard if one line is malformed.
    }
  }
}

const grouped = new Map();
for (const row of rows) {
  const word = normalizeWord(row.headword);
  const existing = grouped.get(word) || {
    word,
    freq: Number(row.freq || 0),
    tier: Number(row.freq_tier || 99),
    parts: [],
    aliases: new Set(),
  };
  existing.freq = Math.max(existing.freq, Number(row.freq || 0));
  existing.tier = Math.min(existing.tier, Number(row.freq_tier || 99));

  for (const form of compactStrings(row.inflections, 10)) {
    const alias = normalizeWord(form);
    if (validHeadword(alias) && alias !== word) existing.aliases.add(alias);
  }

  if (existing.parts.length < 4) {
    existing.parts.push({
      p: String(row.pos || "general"),
      i: typeof row.pron === "string" && row.pron.trim() ? row.pron.trim() : undefined,
      v: compactStrings(row.senses_vi, 4),
      e: compactStrings(row.gloss_en?.length ? row.gloss_en : row.senses_en, 4),
      f: compactStrings(row.inflections, 8),
    });
  }
  grouped.set(word, existing);
}

console.log("[offline-dict] supplementing headwords and examples from Vietnamese Wiktionary...");
let wiktionaryAdded = 0;
let wiktionaryMerged = 0;
let wiktionaryExamplePairs = 0;
try {
  await forEachGzipJsonLine(VIWIKTIONARY_GZ_URL, async (row) => {
    if (String(row?.lang_code || "").toLowerCase() !== "en") return;
    const word = normalizeWord(row?.word);
    if (!validHeadword(word)) return;

    const meanings = wiktionaryMeanings(row);
    if (!meanings.length) return;

    const forms = wiktionaryForms(row);
    const examples = wiktionaryExamples(row);
    const existing = grouped.get(word) || {
      word,
      freq: 0,
      tier: 99,
      parts: [],
      aliases: new Set(),
    };

    const pos = String(row?.pos || "general");
    let part = existing.parts.find((item) => String(item.p || "") === pos);
    if (!part && existing.parts.length < 6) {
      part = {
        p: pos,
        i: wiktionaryIpa(row),
        v: [],
        e: [],
        f: [],
      };
      existing.parts.push(part);
    }

    if (part) {
      part.v = [...new Set([...(part.v || []), ...meanings])].slice(0, 4);
      part.f = [...new Set([...(part.f || []), ...forms])].slice(0, 12);
      if (!part.i) part.i = wiktionaryIpa(row);
      if (examples.length) {
        const existingExamples = Array.isArray(part.x) ? part.x : [];
        part.x = [...existingExamples, ...examples]
          .filter(([english], index, all) => all.findIndex(([candidate]) => candidate === english) === index)
          .slice(0, 2);
        wiktionaryExamplePairs += Math.max(0, part.x.length - existingExamples.length);
      }
    }

    for (const form of forms) {
      if (form !== word) existing.aliases.add(form);
    }

    if (grouped.has(word)) wiktionaryMerged += 1;
    else wiktionaryAdded += 1;
    grouped.set(word, existing);
  }, 70000);
} catch (error) {
  console.warn(`[offline-dict] Vietnamese Wiktionary import failed; continuing with primary dictionary: ${String(error)}`);
}
console.log(`[offline-dict] Wiktionary added ${wiktionaryAdded} headwords and enriched ${wiktionaryMerged} existing headwords; ${wiktionaryExamplePairs} bilingual examples merged.`);

const selected = [...grouped.values()].sort((a, b) => a.word.localeCompare(b.word));
if (selected.length < MIN_EXPECTED_COUNT) {
  throw new Error(
    `Expected at least ${MIN_EXPECTED_COUNT} validated offline entries but only produced ${selected.length}. `
    + "Refusing to build a silently truncated dictionary.",
  );
}
const selectedMap = new Map(selected.map((entry) => [entry.word, entry]));
const priorityCoverage = TOEIC_PRIORITY_WORDS.filter((word) => selectedMap.has(word)).length;

const dictionary = Object.create(null);
const aliases = Object.create(null);
for (const item of selected) {
  dictionary[item.word] = item.parts;
  for (const alias of item.aliases) {
    if (!dictionary[alias] && !aliases[alias]) aliases[alias] = item.word;
  }
}

console.log("[offline-dict] downloading bilingual Tatoeba examples...");
try {
  const corpusZip = await fetchBuffer(TATOEBA_ZIP_URL, 30000);
  const corpusText = extractTextFileFromZip(corpusZip);
  const examples = buildExampleIndex(corpusText, new Set(selectedMap.keys()), aliases);
  let exampleWordCount = 0;
  let exampleSentenceCount = 0;
  for (const [word, pairs] of examples) {
    const parts = dictionary[word];
    if (!parts?.length || !pairs?.length) continue;
    const existingExamples = Array.isArray(parts[0].x) ? parts[0].x : [];
    const mergedExamples = [...existingExamples, ...pairs]
      .filter(([english], index, all) => all.findIndex(([candidate]) => candidate === english) === index)
      .slice(0, 2);
    parts[0].x = mergedExamples;
    if (mergedExamples.length > 0) exampleWordCount += 1;
    exampleSentenceCount += Math.max(0, mergedExamples.length - existingExamples.length);
  }
  console.log(`[offline-dict] embedded ${exampleSentenceCount} bilingual examples across ${exampleWordCount} words.`);
} catch (error) {
  console.warn(`[offline-dict] Tatoeba example import failed; dictionary build will continue: ${String(error)}`);
}

let finalExampleWordCount = 0;
let finalExampleSentenceCount = 0;
for (const parts of Object.values(dictionary)) {
  const pairs = new Set();
  for (const part of parts || []) {
    for (const pair of Array.isArray(part?.x) ? part.x : []) {
      if (pair?.[0]) pairs.add(pair[0]);
    }
  }
  if (pairs.size) {
    finalExampleWordCount += 1;
    finalExampleSentenceCount += pairs.size;
  }
}

function shardKey(value) {
  const first = String(value || "").trim().toLowerCase()[0] || "_";
  return /[a-z0-9]/.test(first) ? first : "_";
}

const shards = new Map();
const getShard = (key) => {
  if (!shards.has(key)) {
    shards.set(key, {
      entries: Object.create(null),
      aliases: Object.create(null),
      ranks: Object.create(null),
    });
  }
  return shards.get(key);
};

for (const [word, parts] of Object.entries(dictionary)) {
  const shard = getShard(shardKey(word));
  shard.entries[word] = parts;
  const source = selectedMap.get(word);
  shard.ranks[word] = [
    Number(source?.tier || 99),
    Number(source?.freq || 0),
  ];
}
for (const [form, lemma] of Object.entries(aliases)) {
  getShard(shardKey(form)).aliases[form] = lemma;
}

await mkdir(path.dirname(OUTPUT), { recursive: true });
await mkdir(OUTPUT_SHARD_DIR, { recursive: true });

const shardKeys = [...shards.keys()].sort();
await Promise.all(shardKeys.map(async (key) => {
  const payload = shards.get(key);
  await writeFile(
    path.join(OUTPUT_SHARD_DIR, `${key}.json`),
    JSON.stringify(payload),
    "utf8",
  );
}));

const headwords = Object.keys(dictionary).sort();
await writeFile(OUTPUT_HEADWORDS_JSON, JSON.stringify(headwords), "utf8");

const meta = {
  schemaVersion: DATA_SCHEMA_VERSION,
  headwordCount: selected.length,
  aliasCount: Object.keys(aliases).length,
  exampleWordCount: finalExampleWordCount,
  exampleSentenceCount: finalExampleSentenceCount,
  shardKeys,
};
await writeFile(OUTPUT_META_JSON, JSON.stringify(meta), "utf8");

const output = `${HEADER}export const OFFLINE_DICTIONARY_SCHEMA_VERSION = ${DATA_SCHEMA_VERSION};\nexport const OFFLINE_DICTIONARY_10000_COUNT = ${selected.length};\nexport const OFFLINE_DICTIONARY_ALIAS_COUNT = ${Object.keys(aliases).length};\nexport const OFFLINE_DICTIONARY_EXAMPLE_WORD_COUNT = ${finalExampleWordCount};\nexport const OFFLINE_DICTIONARY_EXAMPLE_SENTENCE_COUNT = ${finalExampleSentenceCount};\nexport const OFFLINE_DICTIONARY_SHARD_KEYS = ${JSON.stringify(shardKeys)} as const;\n`;
await writeFile(OUTPUT, output, "utf8");

const totalShardBytes = (await Promise.all(
  shardKeys.map(async (key) => Buffer.byteLength(JSON.stringify(shards.get(key)))),
)).reduce((sum, value) => sum + value, 0);

console.log(`[offline-dict] generated ${selected.length} headwords/phrases and ${Object.keys(aliases).length} inflection aliases.`);
console.log(`[offline-dict] example coverage: ${finalExampleWordCount} headwords / ${finalExampleSentenceCount} bilingual sentences.`);
console.log(`[offline-dict] TOEIC/workplace priority coverage: ${priorityCoverage}/${TOEIC_PRIORITY_WORDS.length}.`);
console.log(`[offline-dict] forced coverage: ${FORCE_INCLUDE.filter((word) => dictionary[word]).length}/${FORCE_INCLUDE.length}.`);
console.log(`[offline-dict] wrote ${shardKeys.length} runtime shards + headword index (${(totalShardBytes / 1024 / 1024).toFixed(2)} MiB JSON) to ${OUTPUT_DATA_DIR}.`);
