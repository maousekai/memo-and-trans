import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { inflateRawSync } from "node:zlib";

const OUTPUT = path.resolve("src/data/offlineDictionary10000.generated.ts");
const TARGET_COUNT = 10000;
const THICHHOC_REPO = "thichhoc-org/thichhoc-dict";
const THICHHOC_TREE_URL = `https://api.github.com/repos/${THICHHOC_REPO}/git/trees/main?recursive=1`;
const THICHHOC_ENTRIES_PREFIX = "dict-en-vi/data/entries/";
const TATOEBA_ZIP_URL = "https://www.manythings.org/anki/vie-eng.zip";
const FORCE_INCLUDE = [
  "produce", "company", "manager", "architecture", "consequence", "environment", "government",
  "comprehensive", "subtle", "retain", "ambiguous", "mitigate", "development", "technology",
  "business", "computer", "software", "language", "vocabulary", "example",
];

const HEADER = `// AUTO-GENERATED by scripts/generate-offline-dictionary.mjs\n// Dictionary source: thichhoc-org/thichhoc-dict (CC BY-SA 4.0).\n// Bilingual example source: Tatoeba via ManyThings (CC BY 2.0 FR).\n// Do not edit manually.\n`;

function validHeadword(value) {
  return typeof value === "string" && /^[a-z][a-z' -]{0,47}$/i.test(value.trim());
}

function compactStrings(value, max = 3) {
  if (!Array.isArray(value)) return [];
  return [...new Set(value.map((item) => String(item || "").trim()).filter(Boolean))].slice(0, max);
}

function normalizeWord(value) {
  return String(value || "").trim().toLowerCase().replace(/\s+/g, " ");
}

async function fetchResponse(url, timeoutMs = 20000) {
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);
    try {
      const response = await fetch(url, {
        signal: controller.signal,
        headers: {
          "User-Agent": "LexiGlass-build",
          Accept: "*/*",
        },
      });
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      return response;
    } catch (error) {
      lastError = error;
      if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, attempt * 700));
    } finally {
      clearTimeout(timer);
    }
  }
  throw new Error(`Unable to download ${url}: ${String(lastError)}`);
}

async function fetchText(url, timeoutMs = 20000) {
  return await (await fetchResponse(url, timeoutMs)).text();
}

async function fetchBuffer(url, timeoutMs = 25000) {
  return Buffer.from(await (await fetchResponse(url, timeoutMs)).arrayBuffer());
}

async function mapLimit(items, limit, mapper) {
  const results = new Array(items.length);
  let cursor = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (true) {
      const index = cursor++;
      if (index >= items.length) break;
      results[index] = await mapper(items[index], index);
    }
  });
  await Promise.all(workers);
  return results;
}

async function alreadyGenerated() {
  try {
    const current = await readFile(OUTPUT, "utf8");
    return current.includes(`OFFLINE_DICTIONARY_10000_COUNT = ${TARGET_COUNT}`);
  } catch {
    return false;
  }
}

async function discoverDictionarySources() {
  const tree = JSON.parse(await fetchText(THICHHOC_TREE_URL));
  const paths = (Array.isArray(tree?.tree) ? tree.tree : [])
    .filter((item) => item?.type === "blob" && typeof item?.path === "string")
    .map((item) => item.path)
    .filter((itemPath) => itemPath.startsWith(THICHHOC_ENTRIES_PREFIX));

  const tierOne = paths.filter((itemPath) => /\/freq-tier1-[^/]+\.jsonl$/i.test(itemPath));
  const general = paths.filter((itemPath) => /\/general-[^/]+\.jsonl$/i.test(itemPath));
  const selectedPaths = [...tierOne, ...general].sort();
  if (selectedPaths.length < 20) {
    throw new Error(`Dictionary source discovery returned only ${selectedPaths.length} shards.`);
  }

  return selectedPaths.map(
    (itemPath) => `https://raw.githubusercontent.com/${THICHHOC_REPO}/main/${itemPath}`,
  );
}

function extractTextFileFromZip(buffer) {
  let eocd = -1;
  const minOffset = Math.max(0, buffer.length - 65557);
  for (let offset = buffer.length - 22; offset >= minOffset; offset -= 1) {
    if (buffer.readUInt32LE(offset) === 0x06054b50) {
      eocd = offset;
      break;
    }
  }
  if (eocd < 0) throw new Error("ZIP end-of-central-directory record was not found.");

  const totalEntries = buffer.readUInt16LE(eocd + 10);
  let centralOffset = buffer.readUInt32LE(eocd + 16);
  const candidates = [];

  for (let index = 0; index < totalEntries; index += 1) {
    if (buffer.readUInt32LE(centralOffset) !== 0x02014b50) break;
    const method = buffer.readUInt16LE(centralOffset + 10);
    const compressedSize = buffer.readUInt32LE(centralOffset + 20);
    const uncompressedSize = buffer.readUInt32LE(centralOffset + 24);
    const fileNameLength = buffer.readUInt16LE(centralOffset + 28);
    const extraLength = buffer.readUInt16LE(centralOffset + 30);
    const commentLength = buffer.readUInt16LE(centralOffset + 32);
    const localOffset = buffer.readUInt32LE(centralOffset + 42);
    const fileName = buffer
      .subarray(centralOffset + 46, centralOffset + 46 + fileNameLength)
      .toString("utf8");

    if (/\.txt$/i.test(fileName) && !/\/\s*$/.test(fileName)) {
      candidates.push({ fileName, method, compressedSize, uncompressedSize, localOffset });
    }
    centralOffset += 46 + fileNameLength + extraLength + commentLength;
  }

  const target = candidates.find((item) => /(^|\/)vie\.txt$/i.test(item.fileName))
    || candidates.sort((a, b) => b.uncompressedSize - a.uncompressedSize)[0];
  if (!target) throw new Error("No text corpus was found inside the Tatoeba ZIP archive.");

  const local = target.localOffset;
  if (buffer.readUInt32LE(local) !== 0x04034b50) throw new Error("Invalid ZIP local file header.");
  const localNameLength = buffer.readUInt16LE(local + 26);
  const localExtraLength = buffer.readUInt16LE(local + 28);
  const dataStart = local + 30 + localNameLength + localExtraLength;
  const compressed = buffer.subarray(dataStart, dataStart + target.compressedSize);

  if (target.method === 0) return compressed.toString("utf8");
  if (target.method === 8) return inflateRawSync(compressed).toString("utf8");
  throw new Error(`Unsupported ZIP compression method ${target.method}.`);
}

function buildExampleIndex(corpusText, selectedWords, aliases) {
  const examples = new Map();
  const tokenPattern = /[A-Za-z]+(?:['-][A-Za-z]+)*/g;

  for (const line of corpusText.split(/\r?\n/)) {
    if (!line.trim()) continue;
    const columns = line.split("\t");
    if (columns.length < 2) continue;
    const english = columns[0]?.trim();
    const vietnamese = columns[1]?.trim();
    if (!english || !vietnamese || english.length < 8 || english.length > 180) continue;

    const resolvedInSentence = new Set();
    const tokens = english.match(tokenPattern) || [];
    for (const rawToken of tokens) {
      const token = rawToken.toLowerCase();
      const baseWord = selectedWords.has(token) ? token : aliases[token];
      if (!baseWord || resolvedInSentence.has(baseWord)) continue;
      resolvedInSentence.add(baseWord);

      const current = examples.get(baseWord) || [];
      if (current.length >= 2 || current.some(([existing]) => existing === english)) continue;
      current.push([english, vietnamese]);
      examples.set(baseWord, current);
    }
  }

  return examples;
}

if (await alreadyGenerated()) {
  console.log(`[offline-dict] ${TARGET_COUNT} entries already generated; skipping download.`);
  process.exit(0);
}

console.log("[offline-dict] discovering English-Vietnamese dictionary shards...");
const sourceUrls = await discoverDictionarySources();
console.log(`[offline-dict] downloading ${sourceUrls.length} dictionary shards...`);
const texts = await mapLimit(sourceUrls, 14, async (url) => {
  try {
    return await fetchText(url, 25000);
  } catch (error) {
    console.warn(`[offline-dict] skipped unavailable shard: ${url} (${String(error)})`);
    return "";
  }
});

const rows = [];
for (const text of texts) {
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim()) continue;
    try {
      const row = JSON.parse(line);
      if (!validHeadword(row.headword)) continue;
      if (!Array.isArray(row.senses_vi) || !row.senses_vi.some(Boolean)) continue;
      rows.push(row);
    } catch {
      // Keep processing the rest of an upstream JSONL shard if one line is malformed.
    }
  }
}

const grouped = new Map();
for (const row of rows) {
  const word = normalizeWord(row.headword);
  const existing = grouped.get(word) || {
    word,
    freq: Number(row.freq || 0),
    tier: Number(row.freq_tier || 99),
    parts: [],
    aliases: new Set(),
  };
  existing.freq = Math.max(existing.freq, Number(row.freq || 0));
  existing.tier = Math.min(existing.tier, Number(row.freq_tier || 99));

  for (const form of compactStrings(row.inflections, 10)) {
    const alias = normalizeWord(form);
    if (validHeadword(alias) && alias !== word) existing.aliases.add(alias);
  }

  if (existing.parts.length < 4) {
    existing.parts.push({
      p: String(row.pos || "general"),
      i: typeof row.pron === "string" && row.pron.trim() ? row.pron.trim() : undefined,
      v: compactStrings(row.senses_vi, 4),
      e: compactStrings(row.gloss_en?.length ? row.gloss_en : row.senses_en, 4),
      f: compactStrings(row.inflections, 8),
    });
  }
  grouped.set(word, existing);
}

const ranked = [...grouped.values()].sort(
  (a, b) => a.tier - b.tier || b.freq - a.freq || a.word.localeCompare(b.word),
);
const selectedMap = new Map();
for (const word of FORCE_INCLUDE) {
  const entry = grouped.get(word);
  if (entry) selectedMap.set(word, entry);
}
for (const entry of ranked) {
  if (selectedMap.size >= TARGET_COUNT) break;
  if (!selectedMap.has(entry.word)) selectedMap.set(entry.word, entry);
}
const selected = [...selectedMap.values()].sort((a, b) => a.word.localeCompare(b.word));
if (selected.length !== TARGET_COUNT) {
  throw new Error(`Expected ${TARGET_COUNT} offline words/phrases but only produced ${selected.length}.`);
}

const dictionary = {};
const aliases = {};
for (const item of selected) {
  dictionary[item.word] = item.parts;
  for (const alias of item.aliases) {
    if (!dictionary[alias] && !aliases[alias]) aliases[alias] = item.word;
  }
}

console.log("[offline-dict] downloading bilingual Tatoeba examples...");
try {
  const corpusZip = await fetchBuffer(TATOEBA_ZIP_URL, 30000);
  const corpusText = extractTextFileFromZip(corpusZip);
  const examples = buildExampleIndex(corpusText, new Set(selectedMap.keys()), aliases);
  let exampleWordCount = 0;
  let exampleSentenceCount = 0;
  for (const [word, pairs] of examples) {
    const parts = dictionary[word];
    if (!parts?.length || !pairs?.length) continue;
    parts[0].x = pairs.slice(0, 2);
    exampleWordCount += 1;
    exampleSentenceCount += Math.min(2, pairs.length);
  }
  console.log(`[offline-dict] embedded ${exampleSentenceCount} bilingual examples across ${exampleWordCount} words.`);
} catch (error) {
  console.warn(`[offline-dict] Tatoeba example import failed; dictionary build will continue: ${String(error)}`);
}

await mkdir(path.dirname(OUTPUT), { recursive: true });
const output = `${HEADER}export const OFFLINE_DICTIONARY_10000_COUNT = ${TARGET_COUNT};\nexport const OFFLINE_DICTIONARY_10000 = ${JSON.stringify(dictionary)};\nexport const OFFLINE_DICTIONARY_10000_ALIASES = ${JSON.stringify(aliases)};\n`;
await writeFile(OUTPUT, output, "utf8");
console.log(`[offline-dict] generated ${selected.length} headwords/phrases and ${Object.keys(aliases).length} inflection aliases.`);
console.log(`[offline-dict] forced coverage: ${FORCE_INCLUDE.filter((word) => dictionary[word]).join(", ")}`);
console.log(`[offline-dict] output ${(Buffer.byteLength(output) / 1024 / 1024).toFixed(2)} MiB -> ${OUTPUT}`);
